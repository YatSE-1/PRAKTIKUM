public class OutputVariable {
    public static void main ( String [] Args) {
        int value = 10;
        char x;
        x = 'A';
        System.out.println(value);
        System.out.println("The value of x = " + x);
        //Mendeklarasikan sebuah tipe data dengan nama Variabel
        //Hasil dan tipe data Boolean
        boolean result;
        result = true;
        System.out.println("The value of result = " + result);
        //Mendeklarasikan sebuah tipe data dengan nama Variabel
        //option dan tipe data char
        char option;
        option = 'B'; //memberi nilai 'B' pada variabel option
        System.out.println("The value of option = " + option);
        option = 'C'; //memberi nilai 'C' pada variabel option
        System.out.println("The value of option = " + option);
        //Mendeklarasikan sebuah tipe data dengan nama variabel
        //grade, tipe data double dan nilai inisialisasi 0.0
        double grade = 0.0;
        System.out.println("The value of grade = " + grade);
    }
}